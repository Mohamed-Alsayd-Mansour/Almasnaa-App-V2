-- Service-role-only helpers (revoked from everybody else; PostgREST therefore refuses them to app users)
create function public.archive_begin(p_trigger text, p_user uuid default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_last text;
begin
  update public.archive_runs set status = 'error', finished_at = now(), error = 'timed out'
   where status = 'running' and started_at < now() - interval '10 minutes';
  begin
    insert into public.archive_runs(status, trigger, requested_by) values ('running', p_trigger, p_user) returning id into v_id;
  exception when unique_violation then
    return null;                                           -- another run is in progress
  end;
  select payload_hash into v_last from public.archive_runs where status = 'ok' order by id desc limit 1;
  return jsonb_build_object('id', v_id, 'last_hash', v_last);
end $$;

create function public.archive_snapshot() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'schemaVersion', 2, 'app', 'almasnaa', 'exportedAt', now(), 'source', 'supabase-archive',
    'rooms',    coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from public.rooms x), '[]'),
    'people',   coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from public.people x), '[]'),
    'sessions', coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from public.daily_sessions x), '[]'),
    'entries',  coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from public.daily_entries x), '[]'),
    -- accounts: identity only (no auth data, no password material)
    'accounts', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'username', p.username, 'display_name', p.display_name,
                          'role', p.role, 'status', p.status) order by p.id) from public.profiles p where p.deleted_at is null), '[]'),
    'links',    coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from public.rassas_supervisor_links x), '[]'))
$$;

create function public.archive_finish(p_id bigint, p_status text, p_hash text, p_sha text, p_counts jsonb, p_error text)
returns void language sql security definer set search_path = public as $$
  update public.archive_runs set status = p_status, finished_at = now(), payload_hash = p_hash, commit_sha = p_sha,
         counts = p_counts, error = left(p_error, 300)
   where id = p_id and status = 'running'
$$;
