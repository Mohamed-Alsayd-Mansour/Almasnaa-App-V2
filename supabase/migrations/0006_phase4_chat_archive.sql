-- ---------------------------------------------------------------------
-- 6. v1 option "delete names only": clears the operational name lists, keeps rooms, dailies and entries
--    (entries carry their own name snapshots, so history stays readable).
-- ---------------------------------------------------------------------
create function public.delete_people_only(p_password text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if private.my_role() <> 'admin' then raise exception 'forbidden' using errcode = '42501'; end if;
  if not private.check_backup_password(p_password) then
    return jsonb_build_object('ok', false, 'error', 'invalid_password');
  end if;
  perform set_config('app.audit_skip', 'on', true);
  with x as (delete from public.people returning 1) select count(*) into n from x;
  perform set_config('app.audit_skip', 'off', true);
  insert into public.audit_log(actor_id, actor_role, actor_name, op, entity, changes, view_as_id, view_as_name)
  values (auth.uid(), 'admin', private.name_of(auth.uid()), 'DELETE_NAMES', 'people', jsonb_build_object('people', n),
          private.view_as_id(), private.name_of(private.view_as_id()));
  return jsonb_build_object('ok', true, 'deleted', jsonb_build_object('people', n));
end $$;

