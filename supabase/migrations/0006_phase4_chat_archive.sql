-- ---------- conversations ----------
create function public.chat_open_direct(p_user uuid) returns uuid
language plpgsql security definer set search_path = public as $$
declare v_key text; v_id uuid;
begin
  if private.my_role() is null then raise exception 'forbidden' using errcode = '42501'; end if;
  if p_user is null or p_user = auth.uid() then raise exception 'choose another user'; end if;
  perform 1 from public.profiles where id = p_user and status = 'active' and deleted_at is null;
  if not found then raise exception 'user not found or disabled'; end if;

  v_key := least(auth.uid()::text, p_user::text) || ':' || greatest(auth.uid()::text, p_user::text);
  insert into public.chat_conversations(kind, direct_key, created_by) values ('direct', v_key, auth.uid())
  on conflict (direct_key) do nothing;
  select id into v_id from public.chat_conversations where direct_key = v_key;

  insert into public.chat_members(conversation_id, user_id) values (v_id, auth.uid()), (v_id, p_user)
  on conflict (conversation_id, user_id) do update set left_at = null;
  return v_id;
end $$;

create function public.chat_create_group(p_title text, p_members uuid[]) returns uuid
language plpgsql security definer set search_path = public as $$
declare v_id uuid; v_title text := btrim(coalesce(p_title, ''));
begin
  if private.my_role() is null then raise exception 'forbidden' using errcode = '42501'; end if;
  if length(v_title) not between 1 and 80 then raise exception 'group title must be 1-80 characters'; end if;
  if coalesce(array_length(p_members, 1), 0) = 0 then raise exception 'add at least one member'; end if;
  if array_length(p_members, 1) > 100 then raise exception 'too many members'; end if;

  insert into public.chat_conversations(kind, title, created_by) values ('group', v_title, auth.uid()) returning id into v_id;
  insert into public.chat_members(conversation_id, user_id) values (v_id, auth.uid());
  insert into public.chat_members(conversation_id, user_id)
  select distinct v_id, p.id from public.profiles p
  where p.id = any (p_members) and p.id <> auth.uid() and p.status = 'active' and p.deleted_at is null
  on conflict do nothing;
  return v_id;
end $$;

create function public.chat_add_members(p_conversation uuid, p_members uuid[]) returns int
language plpgsql security definer set search_path = public as $$
declare c public.chat_conversations; n int;
begin
  select * into c from public.chat_conversations where id = p_conversation;
  if not found or c.kind <> 'group' then raise exception 'group not found'; end if;
  if not (private.my_role() = 'admin' or (c.created_by = auth.uid() and private.is_chat_member(p_conversation))) then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  with ins as (
    insert into public.chat_members(conversation_id, user_id)
    select p_conversation, p.id from public.profiles p
    where p.id = any (p_members) and p.status = 'active' and p.deleted_at is null
    on conflict (conversation_id, user_id) do update set left_at = null, last_read_at = now()
      where public.chat_members.left_at is not null
    returning 1)
  select count(*) into n from ins;
  return n;
end $$;

create function public.chat_leave(p_conversation uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform 1 from public.chat_conversations where id = p_conversation and kind = 'group';
  if not found then raise exception 'only group conversations can be left'; end if;
  update public.chat_members set left_at = now()
   where conversation_id = p_conversation and user_id = auth.uid() and left_at is null;
end $$;

create function public.chat_mark_read(p_conversation uuid) returns void
language sql security definer set search_path = public as $$
  update public.chat_members set last_read_at = now()
   where conversation_id = p_conversation and user_id = auth.uid() and left_at is null
$$;

create function public.chat_unread() returns table (conversation_id uuid, unread bigint)
language sql stable security definer set search_path = public as $$
  select m.conversation_id, count(x.id)
  from public.chat_members m
  left join public.chat_messages x on x.conversation_id = m.conversation_id
       and x.sender_id <> m.user_id and x.created_at > m.last_read_at
  where m.user_id = auth.uid() and m.left_at is null and private.my_role() is not null
  group by m.conversation_id
$$;

-- ---------- send (text and/or ONE attachment) — atomic and idempotent on the message id ----------
-- p_attachment = {"id": uuid, "path": "<conv>/<msg>/<att>_<name>", "file_name": text, "duration_ms": int|null}
-- The file must already be in Storage; its real size and mime type are read from Storage metadata.
create function public.chat_send(p_conversation uuid, p_message_id uuid, p_body text,
                                 p_attachment jsonb default null, p_mentions uuid[] default '{}')
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_name text; v_kind public.msg_kind := 'text'; v_body text := nullif(btrim(coalesce(p_body, '')), '');
  v_path text; v_att uuid; o record; v_mime text; v_size bigint; v_created timestamptz; ex public.chat_messages;
begin
  if private.my_role() is null then raise exception 'forbidden' using errcode = '42501'; end if;
  if not private.is_chat_member(p_conversation) then raise exception 'not a member of this conversation' using errcode = '42501'; end if;
  if p_message_id is null then raise exception 'message id required'; end if;

  -- retry of a message that already reached the server: return it, create nothing
  select * into ex from public.chat_messages where id = p_message_id;
  if found then
    if ex.sender_id <> auth.uid() or ex.conversation_id <> p_conversation then
      raise exception 'forbidden' using errcode = '42501';
    end if;
    return jsonb_build_object('ok', true, 'duplicate', true, 'created_at', ex.created_at);
  end if;

  if v_body is not null and length(v_body) > 4000 then raise exception 'message is too long'; end if;

  if p_attachment is not null and jsonb_typeof(p_attachment) = 'object' then
    v_att  := (p_attachment->>'id')::uuid;
    v_path := p_attachment->>'path';
    if v_att is null or v_path is null then raise exception 'bad attachment'; end if;
    if v_path not like p_conversation::text || '/' || p_message_id::text || '/' || v_att::text || '\_%' then
      raise exception 'attachment path does not belong to this message' using errcode = '42501';
    end if;
    select name, metadata into o from storage.objects where bucket_id = 'chat-attachments' and name = v_path;
    if not found then raise exception 'file was not uploaded'; end if;
    v_mime := lower(coalesce(o.metadata->>'mimetype', ''));
    v_size := coalesce((o.metadata->>'size')::bigint, 0);
    v_kind := private.chat_kind_for_mime(v_mime);
    if v_kind is null then raise exception 'file type is not allowed'; end if;
    if v_size <= 0 or v_size > private.chat_max_bytes(v_kind) then raise exception 'file is too large for its type'; end if;
  elsif v_body is null then
    raise exception 'empty message';
  end if;

  v_name := coalesce(private.name_of(auth.uid()), '');
  insert into public.chat_messages(id, conversation_id, sender_id, sender_name, kind, body)
  values (p_message_id, p_conversation, auth.uid(), v_name, v_kind, v_body)
  returning created_at into v_created;

  if v_att is not null then
    insert into public.chat_attachments(id, message_id, conversation_id, storage_path, file_name, mime_type, size_bytes, duration_ms)
    values (v_att, p_message_id, p_conversation, v_path,
            left(coalesce(nullif(btrim(p_attachment->>'file_name'), ''), 'file'), 200), v_mime, v_size,
            nullif(p_attachment->>'duration_ms', '')::int);
  end if;

  -- mentions: stable ids of ACTIVE users only; the sender is never notified about himself
  insert into public.chat_mentions(message_id, user_id)
  select p_message_id, p.id from public.profiles p
  where p.id = any (coalesce(p_mentions, '{}')) and p.id <> auth.uid() and p.status = 'active' and p.deleted_at is null
  limit 20
  on conflict do nothing;

  insert into public.notifications(recipient_id, kind, message_id, conversation_id, actor_name, summary)
  select mt.user_id, 'mention', p_message_id, p_conversation, v_name,
         case when private.chat_member_of(mt.user_id, p_conversation) then left(coalesce(v_body, ''), 140) end
  from public.chat_mentions mt where mt.message_id = p_message_id
  on conflict do nothing;

  update public.chat_conversations set last_message_at = v_created where id = p_conversation;
  update public.chat_members set last_read_at = v_created where conversation_id = p_conversation and user_id = auth.uid();
  return jsonb_build_object('ok', true, 'duplicate', false, 'created_at', v_created);
end $$;

