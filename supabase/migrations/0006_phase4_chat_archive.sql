create type public.chat_kind as enum ('direct', 'group');
create type public.msg_kind  as enum ('text', 'audio', 'image', 'video', 'file');

create table public.chat_conversations (
  id              uuid primary key default gen_random_uuid(),
  kind            public.chat_kind not null,
  title           text,
  direct_key      text unique,                         -- "<smaller uuid>:<larger uuid>" => one DM per pair
  created_by      uuid not null references public.profiles(id),
  created_at      timestamptz not null default now(),
  last_message_at timestamptz,
  constraint chat_kind_shape check (
    (kind = 'direct' and direct_key is not null and title is null) or
    (kind = 'group'  and direct_key is null and length(btrim(coalesce(title, ''))) between 1 and 80))
);

create table public.chat_members (
  conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
  user_id         uuid not null references public.profiles(id),
  joined_at       timestamptz not null default now(),
  last_read_at    timestamptz not null default now(),   -- read state (messages newer than this are unread)
  left_at         timestamptz,
  primary key (conversation_id, user_id)
);
create index chat_members_user on public.chat_members(user_id) where left_at is null;

create table public.chat_messages (
  id              uuid primary key,                     -- generated by the client => retry-safe (no duplicates)
  conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
  sender_id       uuid not null references public.profiles(id),
  sender_name     text not null,                        -- name snapshot at send time
  kind            public.msg_kind not null,
  body            text check (body is null or length(body) <= 4000),
  created_at      timestamptz not null default now(),   -- SERVER time
  constraint chat_text_has_body check (kind <> 'text' or length(btrim(coalesce(body, ''))) > 0)
);
create index chat_messages_conv_time on public.chat_messages(conversation_id, created_at desc);

create table public.chat_attachments (
  id              uuid primary key,
  message_id      uuid not null references public.chat_messages(id) on delete cascade,
  conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
  storage_path    text not null unique,                 -- <conversation>/<message>/<attachment>_<safe name>
  file_name       text not null,
  mime_type       text not null,                        -- taken from Storage metadata, not from the client
  size_bytes      bigint not null check (size_bytes > 0),
  duration_ms     integer check (duration_ms is null or duration_ms >= 0),
  created_at      timestamptz not null default now()
);
create index chat_attachments_msg on public.chat_attachments(message_id);

create table public.chat_mentions (
  message_id uuid not null references public.chat_messages(id) on delete cascade,
  user_id    uuid not null references public.profiles(id),   -- stable id, never the display name
  primary key (message_id, user_id)
);

-- ---------- helpers ----------
create function private.is_chat_member(p_conv uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select private.my_role() is not null
     and exists (select 1 from public.chat_members m
                 where m.conversation_id = p_conv and m.user_id = auth.uid() and m.left_at is null)
$$;

-- safe extraction of the conversation id from a storage path (never throws on junk names)
create function private.chat_conv_of_path(p_name text) returns uuid
language sql immutable as $$
  select case when p_name ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[^/]+$'
              then split_part(p_name, '/', 1)::uuid end
$$;

create function private.chat_kind_for_mime(p_mime text) returns public.msg_kind
language sql immutable as $$
  select case
    when p_mime in ('image/jpeg','image/png','image/webp','image/gif','image/heic') then 'image'::public.msg_kind
    when p_mime in ('audio/mpeg','audio/mp4','audio/aac','audio/ogg','audio/webm','audio/wav','audio/x-wav','audio/x-m4a','audio/m4a') then 'audio'::public.msg_kind
    when p_mime in ('video/mp4','video/quicktime','video/webm') then 'video'::public.msg_kind
    when p_mime in ('application/pdf','application/vnd.openxmlformats-officedocument.wordprocessingml.document') then 'file'::public.msg_kind
  end
$$;

create function private.chat_max_bytes(p_kind public.msg_kind) returns bigint
language sql immutable as $$
  select case p_kind when 'image' then 10485760 when 'audio' then 15728640
                     when 'video' then 52428800 when 'file' then 20971520 else 0 end
$$;

grant execute on function private.is_chat_member(uuid), private.chat_conv_of_path(text),
  private.chat_kind_for_mime(text), private.chat_max_bytes(public.msg_kind) to authenticated;

